#!/usr/bin/env python3
"""Make the photo library's web copies from content/library.json.

For each photo: convert (HEIC via macOS `sips`), fix rotation, strip all metadata (GPS, camera),
and write assets/img/library/<id>.jpg (1600 px long edge) and <id>-t.jpg (480 px).
Then write assets/library-data.js (window.LIBRARY) for admin/photos.html.
Refuses any photo under 1200 px on its long edge (the library only keeps sharp photos).

Run on the Mac with Dropbox and Google Drive synced:  python3 tools/photo-library.py
Needs Pillow (pip3 install pillow).
"""
import json, os, subprocess, sys, tempfile
from PIL import Image, ImageOps

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CLOUD = os.path.expanduser("~/Library/CloudStorage")
OUT = os.path.join(ROOT, "assets/img/library")
MIN_LONG = 1200

lib = json.load(open(os.path.join(ROOT, "content/library.json")))
os.makedirs(OUT, exist_ok=True)
tmp = tempfile.mkdtemp()
items, problems = [], []

for p in lib["photos"]:
    src = os.path.join(CLOUD, p["src"])
    if not os.path.exists(src):
        problems.append(f"missing: {p['src']}"); continue
    if src.lower().endswith(".heic"):
        conv = os.path.join(tmp, p["id"] + ".jpg")
        subprocess.run(["sips", "-s", "format", "jpeg", src, "--out", conv], check=True, capture_output=True)
        src = conv
    im = ImageOps.exif_transpose(Image.open(src)).convert("RGB")
    w, h = im.size
    if max(w, h) < MIN_LONG:
        problems.append(f"too small ({w}x{h}): {p['id']}"); continue
    for suffix, size, q in (("", 1600, 82), ("-t", 480, 78)):
        c = im.copy(); c.thumbnail((size, size), Image.LANCZOS)
        c.save(os.path.join(OUT, f"{p['id']}{suffix}.jpg"), quality=q, optimize=True, progressive=True)
    folder, name = os.path.split(p["src"])
    items.append({**{k: v for k, v in p.items() if k != "src"}, "w": w, "h": h,
                  "where": folder.replace("Dropbox/", "Dropbox › ").replace("GoogleDrive-vincentjacobbi@gmail.com/My Drive/", "Google Drive › ").replace("/", " › "),
                  "file": name})

# Remove web copies for photos no longer in the catalog.
keep = {f"{i['id']}{s}.jpg" for i in items for s in ("", "-t")}
for f in os.listdir(OUT):
    if f.endswith(".jpg") and f not in keep:
        os.remove(os.path.join(OUT, f))

data = {"tags": lib["tags"], "photos": items, "leftOut": lib["leftOut"]}
with open(os.path.join(ROOT, "assets/library-data.js"), "w") as f:
    f.write("// Generated by tools/photo-library.py from content/library.json. Do not edit by hand.\n")
    f.write("window.LIBRARY = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n")

print(f"{len(items)} photos written")
for x in problems:
    print("  !", x)
sys.exit(1 if problems else 0)
